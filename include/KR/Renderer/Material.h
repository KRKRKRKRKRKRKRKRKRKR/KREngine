#pragma once

#include <DirectXMath.h>

namespace KR
{
    // 物ごとの「質感」。DrawMesh / DrawSkinnedMesh / AnimatedModel::Draw に渡す(渡さなければ、既定の材質 = 今までの見た目)
    // 光の当たり方(ハイライトの強さ・鋭さ・色)を物ごとに変える。形の色(頂点の色・画像)は、これとは別
    struct Material
    {
        // 物の色に掛ける色(拡散の色)。(1, 1, 1) = そのまま。赤くしたい物は (1, 0.3, 0.3) など
        DirectX::XMFLOAT3 diffuseColor = { 1.0f, 1.0f, 1.0f };

        // ハイライト(光の反射のつや)の色。(1, 1, 1) = 光の色そのまま。金属のように、物の色を付けたいときは、その色にする
        DirectX::XMFLOAT3 specularColor = { 1.0f, 1.0f, 1.0f };

        // ハイライトの鋭さ。大きいほど、小さく鋭い点になる(プラスチック 32・金属 100 くらい。1 〜 256)
        float shininess = 32.0f;

        // ハイライトの強さ。0 = ハイライトなし(既定。今までと同じ見た目)。1 で、はっきり出る
        float specularStrength = 0.0f;

        // トゥーン(アニメ調)。光の当たり方を、なめらかな明暗ではなく、「段階の帯」に切る。0(既定)= なめらか(今までの見た目)・2 〜 16 = 帯の数
        // (1 は、0 と同じ扱い)。帯にするのは、光の当たり具合(拡散)で、物の色や影の濃さは、変えない。ハイライトは、はっきりした点になる
        int toonSteps = 0;

        // 帯の境目のなめらかさ(0 〜 0.5)。0 = くっきり・大きいほど、境目がぼやける。トゥーンのときだけ効く
        float toonSoftness = 0.05f;

        // true = 光・影・フォグの影響を受けない(物の色 × 画像 × diffuseColor が、そのまま、画面の色になる)。画面に固定して出す UI の物(ゲージ・文字)用
        //   夜(暗い光)でも、決めた色のまま出る。ハイライト・トゥーンも、効かない。既定は false(今までの見た目)
        bool unlit = false;

        // true = カメラ固定(画面に貼り付ける)。DrawMesh に渡す行列を、「ワールド」ではなく「カメラの座標」として扱う
        //   カメラの座標:カメラが原点・前が +Z・右が +X・上が +Y(メートル)。ビュー行列(カメラの位置・向き・傾き)を掛けずに、プロジェクション(遠近)だけを掛ける
        //   → カメラがどこへ動いても・傾いても、画面の同じ場所に出る。世界の座標(Z が数千 m でも)を経由しないので、桁落ちで、ぶれない
        //   例:カメラの前 10 m・画面の右端 = (Renderer::GetViewExtent(10).halfWidth × 0.9, 0, 10) に置く
        //   光・影・フォグの計算には、世界の位置が要るので、cameraSpace は、unlit を含む(unlit を false にしても、true として扱う)
        bool cameraSpace = false;
    };
}
